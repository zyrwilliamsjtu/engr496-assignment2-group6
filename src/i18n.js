  function text(original, ...values) {
    const template = language === 'zh' ? messages.get(original) ?? group6Chinese.get(original) ?? original : original;
    return values.length ? template.replace(/\{(\d+)\}/g, (part, index) => values[index] ?? part) : template;
  }

  function content(original) {
    return language === 'zh' ? group6Chinese.get(original) ?? original : original;
  }

  // Capture authored HTML before application renderers replace any descendants.
  const staticText = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const value = node.nodeValue.trim();
    if (!messages.has(value)) continue;
    const parent = node.parentElement;
    if (parent.tagName === 'OPTION' && !parent.hasAttribute('value')) parent.value = value;
    staticText.push([node, node.nodeValue, value]);
  }
  const staticAttributes = [];
  for (const element of document.querySelectorAll('[placeholder], [aria-label]')) {
    for (const name of ['placeholder', 'aria-label']) {
      if (element.hasAttribute(name)) staticAttributes.push([element, name, element.getAttribute(name)]);
    }
  }
  const title = document.title;
  const toggle = document.getElementById('languageToggle');

  function apply() {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    document.title = text(title);
    toggle.textContent = language === 'zh' ? 'English' : '中文';
    toggle.setAttribute('aria-label', language === 'zh' ? 'Switch to English' : '切换到简体中文');
    toggle.lang = language === 'zh' ? 'en' : 'zh-CN';
    for (const [node, original, value] of staticText) {
      node.nodeValue = original.replace(value, text(value));
    }
    for (const [element, name, value] of staticAttributes) element.setAttribute(name, text(value));
  }

  return {
    text,
    content,
    apply,
    get chinese() { return language === 'zh'; },
    toggle() {
      language = language === 'zh' ? 'en' : 'zh';
      try { localStorage.setItem(storageKey, language); } catch {}
      apply();
    }
  };
